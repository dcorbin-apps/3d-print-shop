import { describe, it, expect } from '@jest/globals';
import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import * as path from 'node:path';
import { ENDS_BYTES, changesColour, endsOf } from '../../src/asAnOctoPrint';
import { pictureOf } from '../../src/jobPicture';
import { slicedPlate } from '../../src/slicedPlate';

// AIDEV-NOTE: (assumption test) the one thing `slicedPlate` cannot say about itself - that the
// spellings it looks for are the spellings a real plate actually uses. Everything in slicedPlate.ts
// was written from what somebody else's tool is BELIEVED to write; this is a plate that tool really
// produced, and it is the only place in this repository that a claim about that format is measured
// rather than asserted.
//
// It reads through `endsOf` on purpose. A test that read the file its own way would pin the format
// and not the shop's ability to find it in one - which is the half that breaks when a plate grows.
describe('what a plate a real tool wrote actually says', () => {
  // Jest's own answer for where this file is, because `import.meta` is not on in this transform and
  // a path from the working directory would depend on where somebody ran the suite from.
  const PLATE = path.resolve(path.dirname(expect.getState().testPath ?? ''), 'aRealPlate.gcode');

  it('says what wrote it, in the shape the shop decides whether to read it by', async () => {
    expect(await endsOf(PLATE)).toMatch(/^; generated by \S+ \S+ on /m);
  });

  it('is read for its filament, its estimate and the bed it was sliced for', async () => {
    expect(slicedPlate(await endsOf(PLATE))).toEqual({
      read: true,
      filaments: ['Generic PLA @PGIS'],
      estimatedPrintSeconds: 359,
      requiredBuildVolume: { x: 250, y: 210, z: 220 },
    });
  });

  // The plate carries QOI pictures larger than its PNG, and those are for the printer's own screen.
  it('is pictured by the PNG it embedded, which is a real one', async () => {
    const picture = await pictureOf(createReadStream(PLATE));

    expect(picture.contentType).toBe('image/png');
    expect([picture.bytes.readUInt32BE(16), picture.bytes.readUInt32BE(20)]).toEqual([380, 285]);
  });

  // What the window costs is bounded; what it has to reach is not, and only a real file says which.
  it('keeps everything worth reading inside the window the shop reads', async () => {
    const { size } = await stat(PLATE);
    const settingsAt = (await endsOf(PLATE)).indexOf('; filament_settings_id = ');

    expect(size).toBeGreaterThan(ENDS_BYTES);
    expect(settingsAt).toBeGreaterThan(-1);
  });

  // The material class sits beside the profile's name and is not it: every PLA on the shelf shares it.
  it('carries a material class beside the profile, which is not taken for the filament', async () => {
    const ends = await endsOf(PLATE);

    expect(ends).toContain('; filament_type = PLA');
    expect(slicedPlate(ends)).toMatchObject({ read: true, filaments: ['Generic PLA @PGIS'] });
  });
});

// AIDEV-NOTE: (assumption test) the same tool's plate with one colour change put in at a layer. What
// is pinned is that the marker `isColourChange` looks for is the one it really writes, and that a
// plate with none - the one above - is not taken for one.
describe('what a plate with a colour change in it actually says', () => {
  const HERE = path.dirname(expect.getState().testPath ?? '');

  it('is found to stop for somebody to change the filament', async () => {
    expect(await changesColour(path.resolve(HERE, 'aColourChangePlate.gcode'))).toBe(true);
  });

  it('is not confused with a plate that never stops', async () => {
    expect(await changesColour(path.resolve(HERE, 'aRealPlate.gcode'))).toBe(false);
  });

  it('is read for its filament like any other plate', async () => {
    expect(slicedPlate(await endsOf(path.resolve(HERE, 'aColourChangePlate.gcode')))).toMatchObject({ read: true, filaments: ['PLA-Red'] });
  });
});
